#!/usr/bin/env node
// Writes the drawing data of Filet's folder and file-type icons from the icon mock, the page they
// were designed and approved in.
//
// The mock draws every icon from SVG path data, and that path data is exactly what Compose and
// android.graphics both read. So the app does not redraw the icons: this script runs the mock's
// own drawing code, takes its tables, and writes them out as Kotlin. A change to the art is made in
// the mock, looked at, approved, and carried across by running this again. Nothing is retyped.
//
//   node tools/make-icon-art.mjs            write app/.../icons/IconArtData.kt
//   node tools/make-icon-art.mjs --check    exit 1 when the written file is not what the mock gives
//
// The mock is docs/design/mockups/filet-browser-icons-mock.html. FILET_ICON_MOCK points at it elsewhere.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MOCK = process.env.FILET_ICON_MOCK || join(ROOT, "docs", "design", "mockups", "filet-browser-icons-mock.html");
const OUT = join(ROOT, "app/src/main/java/dev/niccc2007/filet/icons/IconArtData.kt");
const check = process.argv.includes("--check");

if (!existsSync(MOCK)) {
  console.log(`SKIP: the icon mock is not on this machine (${MOCK}). Set FILET_ICON_MOCK to point at it.`);
  process.exit(0);
}

// ── run the mock's script with a page that answers everything and does nothing ──
const html = readFileSync(MOCK, "utf8");
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
if (!scripts.length) throw new Error("no script in the mock");

const inert = () => {
  const fn = function () {};
  const p = new Proxy(fn, {
    get(_, key) {
      if (key === Symbol.toPrimitive) return () => "";
      if (key === Symbol.iterator) return function* () {};
      if (key === "then") return undefined;
      return p;
    },
    set() { return true; },
    apply() { return p; },
    construct() { return p; },
  });
  return p;
};
const page = inert();
const sandbox = {
  document: page, localStorage: { getItem: () => null, setItem() {} },
  location: { hash: "" }, navigator: page, console, URLSearchParams,
};
sandbox.window = sandbox;
vm.createContext(sandbox);
const TAKE = ["ACC", "COLOUR_NAMES", "GLYPHS", "FAMILIES", "SHORT", "BACK", "FLAP", "SLOT", "SUB", "DEFS", "EMBLEMS", "RICH", "DEFAULTS"];
vm.runInContext(`${scripts.join("\n")}\n;globalThis.__art = { ${TAKE.join(", ")} };`, sandbox, { filename: MOCK });
const { ACC, COLOUR_NAMES, GLYPHS, FAMILIES, SHORT, BACK, FLAP, SLOT, SUB, DEFS, EMBLEMS, RICH, DEFAULTS } = sandbox.__art;

// The gradients, read back out of the <defs> the mock writes. Only the named ones: the accent
// ramps are rebuilt from the accents, and the photo skies are the mock's stand-ins for pictures.
const GRADS = {};
for (const m of DEFS.matchAll(/<(linear|radial)Gradient id="([^"]+)"[^>]*>(.*?)<\/(?:linear|radial)Gradient>/g)) {
  const [, type, id, body] = m;
  if (/^(acc|bb|bf|bi)-/.test(id)) continue;
  GRADS[id] = {
    radial: type === "radial",
    stops: [...body.matchAll(/offset="([\d.]+)" stop-color="([^"]+)"(?: stop-opacity="([\d.]+)")?/g)]
      .map(([, o, c, a]) => [+o, c, a == null ? 1 : +a]),
  };
}

// ── write it as Kotlin ──
const q = (s) => JSON.stringify(s);
const hex = (c) => {
  let h = c.replace("#", "").toUpperCase();
  if (h.length === 3) h = [...h].map((x) => x + x).join("");
  if (h.length !== 6) throw new Error("not a colour: " + c);
  return "0xFF" + h;
};
const f = (v) => {
  const s = String(+(+v).toFixed(3));
  return s + "f";
};
const part = (p) => {
  const args = [q(p.d)];
  if (p.s) args.push(`stroke = ${f(p.s)}`);
  if (p.e) args.push("evenOdd = true");
  if (p.o != null) args.push(`alpha = ${f(p.o)}`);
  if (p.tone === "light") args.push("light = true");
  return `GlyphPart(${args.join(", ")})`;
};
const rich = (p) => {
  const args = [`'${p.t}'`, q(p.d)];
  if (p.s) args.push(`stroke = ${f(p.s)}`);
  if (p.e) args.push("evenOdd = true");
  if (p.o != null) args.push(`alpha = ${f(p.o)}`);
  return `RichPart(${args.join(", ")})`;
};

const lines = [
  "// GENERATED by tools/make-icon-art.mjs from the icon mock. Do not edit: change the mock and run it again.",
  "package dev.niccc2007.filet.icons",
  "",
  "/** The accent ramps, light to deep. */",
  "internal val ACCENTS: Map<String, Accent> = mapOf(",
  ...Object.entries(ACC).map(([k, [a, b, c]]) => `    ${q(k)} to Accent(${hex(a)}, ${hex(b)}, ${hex(c)}),`),
  ")",
  "",
  "/** What each accent is called where a person picks one. */",
  "internal val COLOUR_NAMES: Map<String, String> = mapOf(",
  ...Object.keys(ACC).map((k) => `    ${q(k)} to ${q(COLOUR_NAMES[k] ?? k)},`),
  ")",
  "",
  "/** The named gradients, top to bottom of the shape they fill: offset, colour, opacity. */",
  "internal val GRADIENTS: Map<String, Gradient> = mapOf(",
  ...Object.entries(GRADS).map(([id, g]) =>
    `    ${q(id)} to Gradient(${g.radial}, listOf(${g.stops.map(([o, c, a]) => `Stop(${f(o)}, ${hex(c)}, ${f(a)})`).join(", ")})),`),
  ")",
  "",
  "/** The type glyphs, on a 24-unit box. */",
  "internal val TYPE_GLYPHS: Map<String, List<GlyphPart>> = mapOf(",
];
for (const [k, parts] of Object.entries(GLYPHS)) {
  lines.push(`    ${q(k)} to listOf(`);
  for (const p of parts) lines.push(`        ${part(p)},`);
  lines.push("    ),");
}
lines.push(
  ")",
  "",
  "/** Each icon family: what it is called, its accent and its glyph, by the name `FileTypes` gives a type's icon. */",
  "internal val TYPE_FAMILIES: Map<String, TypeFamily> = mapOf(",
  ...Object.entries(FAMILIES).map(([k, v]) => `    ${q(k)} to TypeFamily(${q(v.label)}, ${q(v.acc)}, ${v.glyph ? q(v.glyph) : "null"}),`),
  ")",
  "",
  "/** The short form of a name too long for the tag. */",
  "internal val TAG_SHORT: Map<String, String> = mapOf(",
  ...Object.entries(SHORT).map(([k, v]) => `    ${q(k)} to ${q(v)},`),
  ")",
  "",
  "/** The folder's back and front, on its own 108-unit grid. */",
  `internal const val FOLDER_BACK = ${q(BACK)}`,
  `internal const val FOLDER_FRONT = ${q(FLAP)}`,
  "",
  "/** Where a thing stands in the folder: centre x, centre y, lean in degrees. P is a thing standing alone. */",
  "internal val FOLDER_SLOTS: Map<Char, Slot> = mapOf(",
  ...Object.entries(SLOT).map(([k, [x, y, r]]) => `    '${k}' to Slot(${f(x)}, ${f(y)}, ${f(r)}),`),
  ")",
  "",
  "/** A folder standing in a folder, about its centre: back with its tab, the sheet, its lines, the front and its lips. */",
  `internal const val SUB_BACK = ${q(SUB.back)}`,
  `internal const val SUB_SHEET = ${q(SUB.sheet)}`,
  `internal val SUB_LINES: List<String> = listOf(${SUB.lines.map(q).join(", ")})`,
  `internal const val SUB_FRONT = ${q(SUB.front)}`,
  `internal const val SUB_LIP = ${q(SUB.lip)}`,
  `internal const val SUB_TAB_LIP = ${q(SUB.tabLip)}`,
  "",
  "/** The emblems a folder can wear, as glyphs on a 24-unit box, in the order the picker shows them. */",
  "internal val EMBLEMS: List<Emblem> = listOf(",
);
for (const e of EMBLEMS) {
  lines.push(`    Emblem(${q(e.id)}, ${q(e.label)}, ${q(e.group)}, listOf(`);
  for (const p of e.parts) lines.push(`        ${part(p)},`);
  lines.push("    )),");
}
lines.push(
  ")",
  "",
  "/** The emblems drawn as scenes for the front of a folder, on a 40 by 30 box. */",
  "internal val RICH_EMBLEMS: Map<String, List<RichPart>> = mapOf(",
);
for (const [id, parts] of Object.entries(RICH)) {
  lines.push(`    ${q(id)} to listOf(`);
  for (const p of parts) lines.push(`        ${rich(p)},`);
  lines.push("    ),");
}
lines.push(
  ")",
  "",
  "/** The folders that wear an emblem without being asked: by their path from the top of a drive. */",
  "internal val DEFAULT_FOLDER_ART: List<DefaultFolderArt> = listOf(",
  ...DEFAULTS.map((d) => `    DefaultFolderArt(${q(d.place)}, ${q(d.emblem)}, ${q(d.colour)}),`),
  ")",
  "",
);
const text = lines.join("\n");
const summary = `${Object.keys(FAMILIES).length} families, ${Object.keys(GLYPHS).length} glyphs, ` +
  `${EMBLEMS.length} emblems, ${Object.keys(RICH).length} drawn, ${Object.keys(GRADS).length} gradients, ${DEFAULTS.length} default folders`;

if (check) {
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (have !== text) {
    console.log(`ICONART STALE: ${OUT} is not what the mock gives. Run: node tools/make-icon-art.mjs`);
    process.exit(1);
  }
  console.log(`ICONART OK  (${summary})`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}  (${summary})`);
}
